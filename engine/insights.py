"""Pulls per-post Instagram stats for every enabled page and writes
history/<page>-stats.json (machine) and history/<page>-stats.md (table for Claude and Roy).

Paid promotion distorts reach, so a post counts as boosted if Instagram reports ads on it
(boost_ads_list, when the API exposes it) or if its permalink/shortcode is listed in
ops/boosted.txt. Boosted posts are shown but left out of the organic comparison."""
import datetime, json, os, re, sys
from common import ROOT, PAGES, ig, log

METRICS = ["reach", "views", "likes", "comments", "shares", "saved", "total_interactions"]


def boosted_from_file():
    p = os.path.join(ROOT, "ops", "boosted.txt")
    if not os.path.exists(p):
        return set()
    codes = set()
    for line in open(p, encoding="utf-8"):
        line = line.split("#")[0].strip()
        m = re.search(r"/(?:p|reel)/([A-Za-z0-9_-]+)", line)
        if m:
            codes.add(m.group(1))
        elif line:
            codes.add(line)
    return codes


def shortcode(permalink):
    m = re.search(r"/(?:p|reel)/([A-Za-z0-9_-]+)", permalink or "")
    return m.group(1) if m else ""


def media_insights(page, mid):
    """All metrics in one call; if Instagram rejects one, fall back to one call per metric."""
    try:
        data = ig(page, "GET", f"{mid}/insights", metric=",".join(METRICS))["data"]
        return {d["name"]: d["values"][0]["value"] for d in data}, []
    except Exception:
        out, errs = {}, []
        for m in METRICS:
            try:
                d = ig(page, "GET", f"{mid}/insights", metric=m)["data"][0]
                out[m] = d["values"][0]["value"]
            except Exception as e:
                errs.append(f"{m}: {str(e)[:160].split('access_token')[0]}")
        return out, errs


def ads_on(page, mid):
    try:
        r = ig(page, "GET", mid, fields="boost_ads_list")
        return bool(r.get("boost_ads_list", {}).get("data")) if isinstance(r.get("boost_ads_list"), dict) else bool(r.get("boost_ads_list"))
    except Exception:
        return None   # field not available with this token / API


def rate(n, reach):
    return round(1000 * n / reach, 1) if reach else None


def run_page(page, boosted_codes):
    me = ig(page, "GET", "me", fields="username,followers_count,media_count")
    media = ig(page, "GET", "me/media", fields="id,caption,media_type,media_product_type,permalink,timestamp", limit=50).get("data", [])
    now = datetime.datetime.now(datetime.timezone.utc)
    posts = []
    for m in media:
        ins, errs = media_insights(page, m["id"])
        code = shortcode(m.get("permalink"))
        api_boost = ads_on(page, m["id"])
        ts = datetime.datetime.strptime(m["timestamp"], "%Y-%m-%dT%H:%M:%S%z")
        reach = ins.get("reach") or 0
        posts.append({
            "id": m["id"], "shortcode": code, "permalink": m.get("permalink"), "posted": m["timestamp"],
            "age_days": round((now - ts).total_seconds() / 86400, 1),
            "type": m.get("media_product_type") or m.get("media_type"),
            "title": (m.get("caption") or "").split("\n")[0][:90],
            "boosted": bool(api_boost) or code in boosted_codes,
            "boost_source": "api" if api_boost else ("ops/boosted.txt" if code in boosted_codes else None),
            **ins,
            "shares_per_1k_reach": rate(ins.get("shares", 0), reach),
            "saves_per_1k_reach": rate(ins.get("saved", 0), reach),
            "errors": errs,
        })
    return {"updated": now.isoformat(timespec="minutes"), "username": me.get("username"),
            "followers": me.get("followers_count"), "posts": posts}


def table(rows):
    head = "| posted | post | reach | views | likes | comm. | shares | saves | shares/1k | saves/1k |\n|---|---|---|---|---|---|---|---|---|---|\n"
    f = lambda v: "" if v is None else str(v)
    return head + "".join(
        f"| {p['posted'][:10]} | [{p['title'].replace('|', '/')}]({p['permalink']}) | {f(p.get('reach'))} | {f(p.get('views'))} | "
        f"{f(p.get('likes'))} | {f(p.get('comments'))} | {f(p.get('shares'))} | {f(p.get('saved'))} | "
        f"{f(p['shares_per_1k_reach'])} | {f(p['saves_per_1k_reach'])} |\n" for p in rows)


def write_md(page, s):
    organic = [p for p in s["posts"] if not p["boosted"]]
    ranked = sorted(organic, key=lambda p: ((p["shares_per_1k_reach"] or 0) + (p["saves_per_1k_reach"] or 0)), reverse=True)
    boosted = [p for p in s["posts"] if p["boosted"]]
    young = [p for p in organic if p["age_days"] < 2]
    errs = sorted({e for p in s["posts"] for e in p["errors"]})
    md = [f"# {page} stats ({s['username']}, {s['followers']} followers), updated {s['updated']} UTC\n",
          "Generated by the `insights` Action. Organic posts are ranked by shares + saves per 1,000 reached accounts "
          "(the signals Instagram weighs most). Boosted posts are listed separately and must not be used to judge topics. "
          "Posts younger than 2 days are still growing.\n",
          "## Organic, best first\n", table(ranked)]
    if boosted:
        md += ["\n## Boosted (paid reach, not comparable)\n", table(boosted)]
    if young:
        md.append(f"\nStill growing (< 2 days): {', '.join(p['shortcode'] for p in young)}\n")
    if errs:
        md += ["\n## API errors\n"] + [f"- {e}\n" for e in errs]
    open(os.path.join(ROOT, "history", f"{page}-stats.md"), "w", encoding="utf-8").write("".join(md))


def main():
    codes = boosted_from_file()
    failed = []
    for page, cfg in PAGES.items():
        if not cfg.get("enabled") or not cfg.get("token_secret"):
            continue
        try:
            s = run_page(page, codes)
        except Exception as e:
            failed.append(page)
            log(f"{page}: {str(e)[:300].split('access_token')[0]}")
            continue
        json.dump(s, open(os.path.join(ROOT, "history", f"{page}-stats.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
        write_md(page, s)
        log(f"{page}: {len(s['posts'])} posts")
    if failed:
        sys.exit(f"failed pages: {failed}")


if __name__ == "__main__":
    main()
